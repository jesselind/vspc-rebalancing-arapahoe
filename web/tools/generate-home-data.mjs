import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const webRoot = process.cwd();
const dataDir = path.join(webRoot, "content", "data");
const outDir = path.join(webRoot, "lib", "generated");
const outFile = path.join(outDir, "home-data.ts");

const DATASETS = [
  { id: "vspc-locations", label: "VSPC Locations", fileName: "VSPC Locations.csv" },
  {
    id: "vspc-precinct-distribution",
    label: "VSPC - Precinct Distribution",
    fileName: "VSPC - Precinct Distribution.csv",
  },
  {
    id: "dc-assignment-verification",
    label: "DC Assignment Verification",
    fileName: "DC Assignment Verification.csv",
  },
  { id: "summary-statistics", label: "Summary Statistics", fileName: "Summary Statistics.csv" },
];

function parseCsv(input) {
  const rows = [];
  let row = [];
  let cell = "";
  let inQuotes = false;

  for (let i = 0; i < input.length; i += 1) {
    const ch = input[i];
    const next = input[i + 1];

    if (ch === '"') {
      if (inQuotes && next === '"') {
        cell += '"';
        i += 1;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }

    if (ch === "," && !inQuotes) {
      row.push(cell);
      cell = "";
      continue;
    }

    if ((ch === "\n" || ch === "\r") && !inQuotes) {
      if (ch === "\r" && next === "\n") {
        i += 1;
      }
      row.push(cell);
      rows.push(row);
      row = [];
      cell = "";
      continue;
    }

    cell += ch;
  }

  if (cell.length > 0 || row.length > 0) {
    row.push(cell);
    rows.push(row);
  }

  return rows.filter((r) => r.some((v) => v.trim().length > 0));
}

async function readDataset(fileName) {
  return readFile(path.join(dataDir, fileName), "utf8");
}

async function loadDatasets() {
  const entries = await Promise.all(
    DATASETS.map(async ({ id, label, fileName }) => {
      const raw = await readDataset(fileName);
      const rows = parseCsv(raw);
      const [headers, ...body] = rows;
      if (!headers) {
        return null;
      }
      return { id, label, fileName, headers, rows: body };
    }),
  );
  return entries.filter(Boolean);
}

async function loadPrecinctAssignments() {
  const raw = await readDataset("VSPC - Precinct Distribution.csv");
  const [headers, ...rows] = parseCsv(raw);
  if (!headers) {
    return [];
  }

  const index = Object.fromEntries(headers.map((header, i) => [header.trim(), i]));
  const requiredHeaders = [
    "Precinct",
    "Nearest VSPC",
    "Distance to Nearest VSPC (mi.)",
    "Assigned VSPC",
    "Address",
    "City",
    "State",
    "Zip",
    "Distance to Assigned VSPC (mi.)",
    "Reassigned",
  ];

  for (const header of requiredHeaders) {
    if (typeof index[header] !== "number") {
      throw new Error(`Missing column "${header}" in VSPC - Precinct Distribution.csv`);
    }
  }

  const assignments = [];
  for (const row of rows) {
    const precinct = row[index["Precinct"]]?.trim();
    if (!precinct) {
      continue;
    }
    const reassignedRaw = (row[index["Reassigned"]] ?? "").trim().toLowerCase();
    assignments.push({
      precinct,
      assignedVspc: row[index["Assigned VSPC"]] ?? "",
      address: row[index["Address"]] ?? "",
      city: row[index["City"]] ?? "",
      state: row[index["State"]] ?? "",
      zip: row[index["Zip"]] ?? "",
      distanceMiles: row[index["Distance to Assigned VSPC (mi.)"]] ?? "",
      nearestVspc: row[index["Nearest VSPC"]] ?? "",
      nearestDistanceMiles: row[index["Distance to Nearest VSPC (mi.)"]] ?? "",
      reassigned: reassignedRaw === "true",
    });
  }

  return assignments;
}

const [datasets, precinctAssignments] = await Promise.all([
  loadDatasets(),
  loadPrecinctAssignments(),
]);

const csvFileContents = Object.fromEntries(
  await Promise.all(
    DATASETS.map(async ({ fileName }) => [fileName, await readDataset(fileName)]),
  ),
);

await mkdir(outDir, { recursive: true });

const source = `// Generated by tools/generate-home-data.mjs — do not edit.
import type { CsvDataset, PrecinctAssignment } from "../types";

export const datasets: CsvDataset[] = ${JSON.stringify(datasets, null, 2)};

export const precinctAssignments: PrecinctAssignment[] = ${JSON.stringify(precinctAssignments, null, 2)};

/** Raw CSV text for /api/download (Workers cannot rely on runtime readFile). */
export const csvFileContents: Record<string, string> = ${JSON.stringify(csvFileContents)};
`;

await writeFile(outFile, source, "utf8");
console.log(`Wrote ${path.relative(webRoot, outFile)} (${precinctAssignments.length} precincts).`);
